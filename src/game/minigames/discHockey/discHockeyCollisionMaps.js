const freezeContour = (points) => Object.freeze(
  points.map(([x, y]) => Object.freeze({ x, y })),
);

const createCollisionMap = ({
  id,
  contour,
  goalLineLeft,
  goalLineRight,
  goalTop = 292,
  goalBottom = 474,
  goalOverlapFraction = 0.4,
}) => {
  const frozenContour = freezeContour(contour);
  const xValues = frozenContour.map(({ x }) => x);
  const yValues = frozenContour.map(({ y }) => y);
  return Object.freeze({
    id,
    contour: frozenContour,
    bounds: Object.freeze({
      left: Math.min(...xValues),
      right: Math.max(...xValues),
      top: Math.min(...yValues),
      bottom: Math.max(...yValues),
    }),
    goalLineLeft,
    goalLineRight,
    goalTop,
    goalBottom,
    goalOverlapFraction,
    visible: false,
    goalVisible: false,
  });
};

